#include "asFileNetcdf.h"

asFileNetcdf::asFileNetcdf(const wxString& fileName, const FileMode& fileMode)
    : asFile(fileName, fileMode),
      _fileId(0),
      _status(0),
      _defineMode(false) {
    _struct.format = Classic;
}

asFileNetcdf::~asFileNetcdf() {
    Close();
    wxASSERT(_fileId == 0);
}

bool asFileNetcdf::Open() {
    if (!Find()) return false;

    wxString datetime, generator;

    if (_fileMode != ReadOnly) {
        datetime = asTime::GetStringTime(asTime::NowTimeStruct(asLOCAL), ISOdateTime);
        generator = _("Generated by AtmoSwing ") + g_version;
    }

    switch (_fileMode) {
        case (ReadOnly): {
            _defineMode = false;
            _status = nc_open(_fileName.GetFullPath().mb_str(wxConvUTF8), NC_NOWRITE, &_fileId);
            if (_status) HandleErrorNetcdf();
            _opened = true;
            if (!ParseStruct()) {
                wxLogError(_("Failed parsing the file structure."));
                ClearStruct();
                return false;
            }
            break;
        }
        case (Write): {
            _defineMode = true;
            _status = nc_create(_fileName.GetFullPath().mb_str(wxConvUTF8), NC_NETCDF4 | NC_WRITE, &_fileId);
            if (_status) HandleErrorNetcdf();
            _opened = true;
            if (!ParseStruct()) {
                wxLogError(_("Failed parsing the file structure."));
                ClearStruct();
                return false;
            }
            break;
        }
        case (Replace): {
            _defineMode = true;
            _status = nc_create(_fileName.GetFullPath().mb_str(wxConvUTF8), NC_NETCDF4 | NC_CLOBBER, &_fileId);
            if (_status) HandleErrorNetcdf();
            _opened = true;
            PutAtt("creation_date", datetime);
            PutAtt("origin", generator);
            break;
        }
        case (New): {
            _defineMode = true;
            _status = nc_create(_fileName.GetFullPath().mb_str(wxConvUTF8), NC_NETCDF4 | NC_NOCLOBBER, &_fileId);
            if (_status) HandleErrorNetcdf();
            _opened = true;
            PutAtt("creation_date", datetime);
            PutAtt("origin", generator);
            break;
        }
        default: {
            throw runtime_error(_("No valid NetCdf FileMode has been selected"));
        }
    }

    _opened = true;

    return true;
}

bool asFileNetcdf::Close() {
    // If not already closed
    if (_fileId != 0) {
        CheckDefModeClosed();  // Check that the file is not in define mode
        ClearStruct();
        _status = nc_close(_fileId);
        if (_status) HandleErrorNetcdf();
        _fileId = 0;
    }

    return true;
}

bool asFileNetcdf::ForceClose() {
    CheckDefModeClosed();  // Check that the file is not in define mode
    ClearStruct();
    _status = nc_close(_fileId);
    _fileId = 0;

    return true;
}

void asFileNetcdf::HandleErrorNetcdf() {
    if (_status != NC_NOERR) {
        std::string tmpmessage = nc_strerror(_status);
        wxString wxtmpmessage(tmpmessage.c_str(), wxConvUTF8);
        wxString errorMessage = asStrF(_("NetCDF error in file %s: %s"), _fileName.GetName(), wxtmpmessage);
        throw runtime_error(errorMessage);
    }
}

void asFileNetcdf::DefDim(const wxString& dimName, const size_t& dimSize) {
    wxASSERT(_opened);

    int dimId;

    // Check that the file is in define mode
    CheckDefModeOpen();

    if (dimSize == 0) {
        _status = nc_def_dim(_fileId, dimName.mb_str(wxConvUTF8), NC_UNLIMITED, &dimId);
        if (_status) HandleErrorNetcdf();
        //        dimSize = 0;
    } else {
        _status = nc_def_dim(_fileId, dimName.mb_str(wxConvUTF8), dimSize, &dimId);
        if (_status) HandleErrorNetcdf();
    }
}

void asFileNetcdf::DefVar(const wxString& varName, nc_type dataType, const int& varSize, const vstds& dimNames) {
    wxASSERT(_opened);

    int varId, dimId, nDims;
    vi dimIds;

    // Check that the file is in define mode
    CheckDefModeOpen();

    nDims = (int)dimNames.size();

    for (int i = 0; i < nDims; i++) {
        _status = nc_inq_dimid(_fileId, dimNames[i].data(), &dimId);
        if (_status) HandleErrorNetcdf();
        dimIds.push_back(dimId);
    }

    _status = nc_def_var(_fileId, varName.mb_str(wxConvUTF8), dataType, varSize, &dimIds[0], &varId);
    if (_status) HandleErrorNetcdf();
}

void asFileNetcdf::DefVarDeflate(const wxString& varName, int shuffle, int deflateLevel) {
    wxASSERT(_opened);

    int varId;

    _status = nc_inq_varid(_fileId, varName.mb_str(wxConvUTF8), &varId);
    if (_status) HandleErrorNetcdf();

    _status = nc_def_var_deflate(_fileId, varId, shuffle, 1, deflateLevel);
    if (_status) HandleErrorNetcdf();
}

void asFileNetcdf::PutAtt(const wxString& attName, const wxString& textStr, const wxString& varName) {
    wxASSERT(_opened);

    int attId, varId;

    wxCharBuffer buffer = textStr.ToUTF8();

    // Check that the file is in define mode
    CheckDefModeOpen();

    // Check if global or not
    if ((varName.IsEmpty())) {
        _status = nc_put_att_text(_fileId, NC_GLOBAL, attName.mb_str(wxConvUTF8), strlen(buffer.data()), buffer.data());
        if (_status) HandleErrorNetcdf();
        // Get the ID
        _status = nc_inq_attid(_fileId, NC_GLOBAL, attName.mb_str(wxConvUTF8), &attId);
        if (_status) HandleErrorNetcdf();
    } else {
        _status = nc_inq_varid(_fileId, varName.mb_str(wxConvUTF8), &varId);
        if (_status) HandleErrorNetcdf();
        _status = nc_put_att_text(_fileId, varId, attName.mb_str(wxConvUTF8), strlen(buffer.data()), buffer.data());
        if (_status) HandleErrorNetcdf();
        // Get the ID
        _status = nc_inq_attid(_fileId, varId, attName.mb_str(wxConvUTF8), &attId);
        if (_status) HandleErrorNetcdf();
    }
}

