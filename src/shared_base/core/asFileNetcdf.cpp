wxString asFileNetcdf::GetAttString(const wxString& attName, const wxString& varName) {
    wxASSERT(_opened);

    size_t len;
    wxString attrValue;

    // Check that the file is not in define mode
    CheckDefModeClosed();

    // Check if global attribute or variable attribute
    if (varName.IsEmpty()) {  // Global attribute
        int attId = GetAttId(attName);
        if (attId == asNOT_FOUND) return wxEmptyString;

        // Allocate
        len = _struct.atts[attId].length;
        auto text = new char[len + 1]; /* + 1 for trailing null */

        // Check the given type
        nc_type nctype = _struct.atts[attId].type;
        if (nctype != NC_CHAR) {
            wxDELETEA(text);
            throw runtime_error(asStrF(_("The attribute (%s) type (%d) in file doesn't match the desired type (%d)."),
                                       attName, (int)nctype, (int)NC_CHAR));
        }

        // Get value
        _status = nc_get_att_text(_fileId, NC_GLOBAL, attName.mb_str(wxConvUTF8), text);
        if (_status) HandleErrorNetcdf();

        text[len] = '\0';

        // Copy into a wxString
        attrValue = wxString(text, wxConvUTF8);
        wxASSERT(!attrValue.IsEmpty());
        attrValue.Remove(len);  // Remove the stuff after the end of the string
        wxASSERT(!attrValue.IsEmpty());
        wxDELETEA(text);

    } else {  // Variable attribute
        int varId = GetVarId(varName);
        if (varId == asNOT_FOUND) return wxEmptyString;
        int attId = GetAttId(attName, varName);
        if (attId == asNOT_FOUND) return wxEmptyString;

        // Allocate
        len = _struct.vars[varId].atts[attId].length;
        auto text = new char[len + 1]; /* + 1 for trailing null */

        // Check the given type
        nc_type nctype = _struct.vars[varId].atts[attId].type;
        if (nctype != NC_CHAR) {
            wxDELETEA(text);
            throw runtime_error(
                asStrF(_("The attribute (%s.%s) type (%d) in file doesn't match the desired type (%d)."), varName,
                       attName, (int)nctype, (int)NC_CHAR));
        }

        // Get value
        _status = nc_get_att_text(_fileId, varId, attName.mb_str(wxConvUTF8), text);
        if (_status) HandleErrorNetcdf();

        text[len] = '\0';

        // Copy into a wxString
        attrValue = wxString(text);
        wxASSERT(!attrValue.IsEmpty());
        attrValue.Remove(len);  // Remove the stuff after the end of the string
        wxASSERT(!attrValue.IsEmpty());
        wxDELETEA(text);
    }

    return attrValue;
}

